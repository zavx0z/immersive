/** ColorField показывает публичное использование своего владельца. */
import {afterAll, describe, expect, test} from "bun:test"
import {createHeadless} from "@immersive/headless"
import ColorField from "@immersive-ui-component-field/color"

describe.each([{name: "Основное представление", props: {value: {r: 1, g: 0, b: 0, a: 1}, label: "Параметр"}}])("$name", async ({props}) => {
  const headless = createHeadless({width: 640, height: 400})
  afterAll(() => headless.dispose())
  const element = await headless.render(
    <ColorField
      value={props.value}
      label={props.label}
     />
  )

  test("Содержимое", () => {
    expect(element.textContent, "Представление показывает переданное значение").toContain("Параметр")
  })
})
