/**
Распределение индексов детей по объявленным точкам вставки.
План не содержит DOM-узлов и не монтирует содержимое: потребитель связывает
индексы со своими исходными детьми. Пустые области остаются в результате.

@property slots - Области в порядке входного outlets. Поле name сохраняет
точное имя, а children содержит исходные индексы назначенных детей
в авторском порядке, начиная с нуля.
*/
export interface PlanSlotsOutput {
  slots: readonly {name: string; children: readonly number[]}[]
}
