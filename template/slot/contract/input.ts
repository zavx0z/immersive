/**
Объявленные точки вставки и назначения непосредственных детей получателя.
Имена сравниваются точно, без обрезки пробелов или изменения регистра.
Пустая строка обозначает безымянный слот. Каждый ребёнок назначается ровно
одной объявленной области; отсутствие slot равнозначно пустой строке.

@property outlets - Порядок точек вставки в получателе. Имена уникальны,
включая имя безымянного слота.

@property children - Дети в авторском порядке. Индекс элемента становится
адресом ребёнка в плане; необязательное поле slot задаёт имя области.
*/
export interface PlanSlotsInput {
  outlets: readonly string[]
  children: readonly {slot?: string}[]
}
